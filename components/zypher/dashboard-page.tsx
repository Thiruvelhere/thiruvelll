"use client"

import { useEffect, useState } from "react"
import {
  Activity,
  ArrowRight,
  ArrowUpRight,
  BellRing,
  CheckCircle2,
  Clock3,
  Download,
  FilePlus2,
  Files,
  ShieldAlert,
} from "lucide-react"
import { toast } from "sonner"
import {
  Area,
  AreaChart,
  CartesianGrid,
  Cell,
  Pie,
  PieChart,
  XAxis,
  YAxis,
} from "recharts"
import { Button } from "@/components/ui/button"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import {
  ChartContainer,
  ChartTooltip,
  ChartTooltipContent,
} from "@/components/ui/chart"
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table"
import { PageHeader, StatusBadge } from "./shared"
import {
  APPLICATIONS,
  DEMO_APPLICATION_ID,
  STATUS_CHART_DATA,
  TREND_DATA,
} from "./data"
import { ApplicationDetailDialog } from "./application-detail-dialog"
import { downloadTextReport, exportApplicationsCSV } from "./export-utils"
import type { AppPage } from "./types"

const statusChartConfig = {
  "Ready for review": { label: "Ready for review", color: "var(--status-green)" },
  "Pending review": { label: "Pending review", color: "var(--status-amber)" },
  Flagged: { label: "Flagged", color: "var(--status-red)" },
}

const trendChartConfig = {
  submitted: { label: "Submitted", color: "var(--chart-1)" },
  verified: { label: "Verified", color: "var(--status-green)" },
}

const metricTargets = [
  {
    title: "Total applications",
    target: 248,
    detail: "+8.4% from last month",
    icon: Files,
    tone: "metric-blue",
  },
  {
    title: "Pending review",
    target: 42,
    detail: "12 due for review this week",
    icon: Clock3,
    tone: "metric-amber",
  },
  {
    title: "Flagged for attention",
    target: 17,
    detail: "6 high-priority findings",
    icon: ShieldAlert,
    tone: "metric-red",
  },
  {
    title: "Ready for review",
    target: 189,
    detail: "76% of submitted applications",
    icon: CheckCircle2,
    tone: "metric-green",
  },
]

export function DashboardPage({
  onNavigate,
  onLoadDemo,
}: {
  onNavigate: (page: AppPage) => void
  onLoadDemo: () => void
}) {
  const [selectedAppId, setSelectedAppId] = useState<string | null>(null)
  const [counts, setCounts] = useState([0, 0, 0, 0])

  useEffect(() => {
    const duration = 900
    const steps = 30
    const interval = duration / steps
    let currentStep = 0

    const timer = setInterval(() => {
      currentStep++
      const progress = Math.min(currentStep / steps, 1)
      const easeOut = 1 - Math.pow(1 - progress, 3)

      setCounts(metricTargets.map((m) => Math.round(m.target * easeOut)))

      if (currentStep >= steps) {
        clearInterval(timer)
      }
    }, interval)

    return () => clearInterval(timer)
  }, [])

  const exportOverview = () => {
    const summary = `
================================================================================
AICTE REGULATORY OVERSIGHT PLATFORM - DASHBOARD CYCLE SUMMARY
================================================================================
Academic Cycle:        2026–27
Report Date:           ${new Date().toLocaleDateString("en-IN", { dateStyle: "long" })}
Authorized Officer:    Ananya Verma (Regional Reviewer)

KEY OVERSIGHT METRICS:
--------------------------------------------------------------------------------
Total Applications Submitted:   248 (+8.4% growth)
Ready for Approval / Review:    189 (76.2%)
Pending Compliance Audit:       42
Flagged for Critical Inquiries: 17

STATUS DISTRIBUTION:
  - Ready for Review:           189 institutions
  - Pending Review:              42 institutions
  - Flagged for Review:          17 institutions

MONTHLY SUBMISSION VELOCITY (MAY - OCT 2026):
  May:  18 Submitted | 14 Verified
  Jun:  26 Submitted | 21 Verified
  Jul:  44 Submitted | 36 Verified
  Aug:  68 Submitted | 52 Verified
  Sep:  54 Submitted | 47 Verified
  Oct:  38 Submitted | 32 Verified

================================================================================
Generated by Zypher Oversight System v3.2.1
================================================================================
`
    downloadTextReport(`aicte-cycle-summary-${new Date().toISOString().split("T")[0]}.txt`, summary.trim())
    toast.success("Executive summary exported", {
      description: "Downloaded dashboard metrics report.",
    })
  }

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Oversight workspace · Academic year 2026–27"
        title="Oversight Overview"
        description="Live status of technical education institutions, automated verification signals, and reviewer queues."
      >
        <Button type="button" variant="outline" onClick={exportOverview}>
          <Download data-icon="inline-start" aria-hidden="true" />
          Export overview
        </Button>
        <Button type="button" onClick={() => onNavigate("submission")}>
          <FilePlus2 data-icon="inline-start" aria-hidden="true" />
          New submission
        </Button>
      </PageHeader>

      <section className="metric-grid" aria-label="Application summary">
        {metricTargets.map(({ title, detail, icon: Icon, tone }, idx) => (
          <Card className="metric-card" key={title}>
            <CardContent className="metric-card-content">
              <div className="metric-card-top">
                <div className={`metric-icon ${tone}`}>
                  <Icon aria-hidden="true" />
                </div>
                <span className="metric-period">This cycle</span>
              </div>
              <p className="metric-value font-mono font-bold tracking-tight">{counts[idx]}</p>
              <p className="metric-title">{title}</p>
              <p className="metric-detail">{detail}</p>
            </CardContent>
          </Card>
        ))}
      </section>

      <section className="dashboard-chart-grid" aria-label="Application analytics">
        <Card className="dashboard-card status-card">
          <CardHeader className="dashboard-card-header">
            <div>
              <CardTitle>Application status</CardTitle>
              <CardDescription>Distribution across the current review cycle</CardDescription>
            </div>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onNavigate("applications")}
            >
              View applications
              <ArrowRight data-icon="inline-end" aria-hidden="true" />
            </Button>
          </CardHeader>
          <CardContent className="status-card-content">
            <div className="status-chart-wrap">
              <div className="status-chart-center" aria-hidden="true">
                <span className="font-mono font-bold">248</span>
                <span>Applications</span>
              </div>
              <ChartContainer
                config={statusChartConfig}
                className="status-chart"
                aria-label="Application status: 189 ready for review, 42 pending review, 17 flagged"
              >
                <PieChart accessibilityLayer>
                  <Pie
                    data={STATUS_CHART_DATA}
                    dataKey="value"
                    nameKey="name"
                    innerRadius={72}
                    outerRadius={96}
                    paddingAngle={3}
                    stroke="var(--card)"
                    strokeWidth={4}
                  >
                    {STATUS_CHART_DATA.map((entry) => (
                      <Cell key={entry.name} fill={entry.color} />
                    ))}
                  </Pie>
                  <ChartTooltip
                    content={<ChartTooltipContent nameKey="name" hideLabel />}
                  />
                </PieChart>
              </ChartContainer>
            </div>
            <div className="status-legend" aria-label="Status totals">
              {STATUS_CHART_DATA.map((entry) => (
                <div className="status-legend-row" key={entry.name}>
                  <span className="status-legend-label">
                    <span className="status-legend-dot" style={{ backgroundColor: entry.color }} />
                    {entry.name}
                  </span>
                  <span className="status-legend-value font-mono font-medium">{entry.value}</span>
                </div>
              ))}
              <div className="status-legend-footnote">
                <Activity aria-hidden="true" />
                Updated in real-time
              </div>
            </div>
          </CardContent>
        </Card>

        <Card className="dashboard-card trend-card">
          <CardHeader className="dashboard-card-header">
            <div>
              <CardTitle>Submission velocity</CardTitle>
              <CardDescription>Monthly submissions compared with completed validations</CardDescription>
            </div>
            <span className="chart-period">May – Oct 2026</span>
          </CardHeader>
          <CardContent className="trend-card-content">
            <ChartContainer
              config={trendChartConfig}
              className="trend-chart"
              aria-label="Monthly application submissions and completed checks from May to October 2026"
            >
              <AreaChart
                accessibilityLayer
                data={TREND_DATA}
                margin={{ top: 10, right: 12, left: -18, bottom: 0 }}
              >
                <defs>
                  <linearGradient id="submitted-fill" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="0%" stopColor="var(--color-submitted)" stopOpacity={0.2} />
                    <stop offset="100%" stopColor="var(--color-submitted)" stopOpacity={0} />
                  </linearGradient>
                  <linearGradient id="verified-fill" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="0%" stopColor="var(--color-verified)" stopOpacity={0.15} />
                    <stop offset="100%" stopColor="var(--color-verified)" stopOpacity={0} />
                  </linearGradient>
                </defs>
                <CartesianGrid vertical={false} strokeDasharray="3 5" />
                <XAxis
                  dataKey="month"
                  axisLine={false}
                  tickLine={false}
                  tickMargin={10}
                />
                <YAxis axisLine={false} tickLine={false} tickMargin={8} width={30} />
                <ChartTooltip content={<ChartTooltipContent indicator="line" />} />
                <Area
                  type="monotone"
                  dataKey="submitted"
                  stroke="var(--color-submitted)"
                  strokeWidth={2.5}
                  fill="url(#submitted-fill)"
                  activeDot={{ r: 4, strokeWidth: 0 }}
                />
                <Area
                  type="monotone"
                  dataKey="verified"
                  stroke="var(--color-verified)"
                  strokeWidth={2.5}
                  fill="url(#verified-fill)"
                  activeDot={{ r: 4, strokeWidth: 0 }}
                />
              </AreaChart>
            </ChartContainer>
            <div className="trend-legend">
              <span><i className="trend-dot trend-dot-submitted" />Submitted</span>
              <span><i className="trend-dot trend-dot-verified" />Verified</span>
              <span className="trend-callout"><ArrowUpRight aria-hidden="true" />14% this quarter</span>
            </div>
          </CardContent>
        </Card>
      </section>

      <Card className="dashboard-card recent-card">
        <CardHeader className="dashboard-card-header recent-card-header">
          <div>
            <CardTitle>Recent applications</CardTitle>
            <CardDescription>Latest submissions requiring regional oversight</CardDescription>
          </div>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={() => onNavigate("applications")}
          >
            View all
            <ArrowRight data-icon="inline-end" aria-hidden="true" />
          </Button>
        </CardHeader>
        <CardContent className="table-card-content">
          <Table className="application-table">
            <TableHeader>
              <TableRow>
                <TableHead>Application</TableHead>
                <TableHead>Institution</TableHead>
                <TableHead>Submitted</TableHead>
                <TableHead>Status</TableHead>
                <TableHead className="text-right">Risk score</TableHead>
                <TableHead><span className="sr-only">Actions</span></TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {APPLICATIONS.slice(0, 5).map((application) => (
                <TableRow
                  key={application.id}
                  className="cursor-pointer hover:bg-muted/50 transition-colors"
                  onClick={() => setSelectedAppId(application.id)}
                >
                  <TableCell className="table-id-cell font-mono font-medium text-primary">
                    {application.id}
                  </TableCell>
                  <TableCell>
                    <div className="table-institution">
                      <span className="font-medium">{application.institution}</span>
                      <span className="text-xs text-muted-foreground">{application.applicationType}</span>
                    </div>
                  </TableCell>
                  <TableCell className="table-muted-cell">{application.submittedOn}</TableCell>
                  <TableCell><StatusBadge status={application.status} /></TableCell>
                  <TableCell className="text-right">
                    <span className={`risk-number ${application.riskScore >= 70 ? "risk-number-high" : application.riskScore >= 40 ? "risk-number-medium" : "risk-number-low"}`}>
                      {application.riskScore}
                    </span>
                    <span className="risk-out-of">/ 100</span>
                  </TableCell>
                  <TableCell className="table-action-cell" onClick={(e) => e.stopPropagation()}>
                    <Button
                      type="button"
                      variant="ghost"
                      size="sm"
                      aria-label={`View ${application.id}`}
                      onClick={() => setSelectedAppId(application.id)}
                      className="hover:bg-primary/10 hover:text-primary"
                    >
                      View
                    </Button>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      <div className="dashboard-footer-note">
        <BellRing aria-hidden="true" />
        <span className="font-semibold">Priority review queue:</span>
        <span>Six applications have high-priority findings awaiting officer inspection.</span>
        <Button type="button" variant="link" size="sm" onClick={() => onNavigate("applications")}>
          Open queue
        </Button>
      </div>

      <ApplicationDetailDialog
        applicationId={selectedAppId}
        onClose={() => setSelectedAppId(null)}
        onNavigate={onNavigate}
      />
    </div>
  )
}
